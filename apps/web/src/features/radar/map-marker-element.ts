export function createMapMarkerElement(
  categorySlug: string | null | undefined,
  title: string | undefined,
  verificationStatus: VerificationStatus | undefined,
  onClick: () => void,
): HTMLButtonElement {
  const slug = resolveDisplayCategorySlug(categorySlug, title);
  const color = getMapPinColor(categorySlug, title);
  const svg = ICON_SVG[slug] ?? ICON_SVG.default;

  const verified = verificationStatus === 'VERIFICADO';
  const highRisk = verificationStatus === 'ALTO_RISCO';

  const btn = document.createElement('button');
  btn.type = 'button';
  btn.className = `map-pin map-pin--${slug.replace(/[^a-z0-9-]/g, '')}`;
  btn.setAttribute('aria-label', title ?? 'Leilão');
  btn.style.setProperty('--pin-color', color);
  btn.innerHTML = `
    <span class="map-pin__pulse" aria-hidden="true"></span>
    <span class="map-pin__core">
      <span class="map-pin__icon">${svg}</span>
      ${verified ? '<span class="map-pin__star" title="Verificado">★</span>' : ''}
      ${highRisk ? '<span class="map-pin__risk" title="Alto risco">!</span>' : ''}
    </span>
  `;
  btn.addEventListener('click', (e) => {
    e.stopPropagation();
    onClick();
  });
  return btn;
}
